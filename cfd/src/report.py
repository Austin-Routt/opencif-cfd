#!/usr/bin/env python3
"""Write cfd/results/COMPARISON.md from cfd/results/comparison.json (tables only; every number comes from the JSON).

usage: python3 report.py ARCHIVE_ROOT"""
import sys, os, json

root = sys.argv[1]
R = json.load(open(os.path.join(root, 'cfd', 'results', 'comparison.json')))
L = []
w = L.append
F5, SG = R['five_gap'], R['single_gap']
C = F5['comsol']; G = F5['grid']


def e(x, d=2):
    return ('%.' + str(d) + 'e') % x


w('# Two-code comparison\n')
w('Generated by `cfd/src/report.py` from `cfd/results/comparison.json`, which `cfd/src/compare.py` computes from the '
  'archived COMSOL exports and Python CFD\'s run records. Flows are m³/s for the modeled half width at full '
  'depth; pressures are Pa; widths are µm.\n')
w('## 1. Five-gap slab: COMSOL\n')
w('| Model | Elements | Q_in | Q_c | Q_s | F = 1 − Q_c/Q_in | balance | Σ gap flows / Q_s | max \\|w\\| / max speed at mid-depth |')
w('|---|---:|---|---|---|---|---|---|---|')
for k, r in C.items():
    w('| %s | %d | %s | %s | %s | %.7f | %s | %.5f | %s |' % (k, r['elements'], e(r['Q_in'], 6), e(r['Q_c'], 6),
                                                            e(r['Q_s'], 6), r['F'], e(r['imbalance'], 1),
                                                            r['Q_gap_sum_over_Qs'],
                                                            e(r['middepth_w']['max_abs_w_over_max_speed'], 1)))
w('\nTwo-grid estimate (ASME V&V 20-2009 eqs. 2-4-12 and 2-4-14; Fs = 3, p = 2, r = (N_fine/N_coarse)^(1/3)):\n')
w('| Variant | r | ΔF (fine − coarse) | GCI | u_num = GCI/1.15 | F extrapolated | Q_in extrapolated |')
w('|---|---|---|---|---|---|---|')
for v, t in G['comsol'].items():
    q = G['comsol_Q_in'].get(v[:2]) if v in ('V1', 'V3') else None
    w('| %s | %.4f | %s | %s | %s | %.6f | %s |' % (v, t['r'], e(t['delta'], 4), e(t['GCI'], 3), e(t['u_num'], 3),
                                                  t['extrapolated'], e(q['extrapolated'], 5) if q else '—'))
mr = F5['mesh_realization_V3']
w('\nV3 coarse at fixed mesh settings: preprint tables %.7f (104,651 elements), stored solution %.7f (104,206), '
  're-solved %.7f (104,705); re-solved minus stored %s; their mid-depth fields differ by %.2e (relative L2).\n'
  % (mr['F_preprint_tables'], mr['F_stored_solution'], mr['F_resolved'], e(mr['difference'], 2), mr['field']['rel_l2']))
w('## 2. Five-gap slab: Python CFD\n')
for v in ('V1', 'V3'):
    if v not in F5['python']:
        continue
    w('**%s**\n' % v)
    w('| Run | Scale | Tets | DOF | MINRES residual | Q_in | F | balance | Σ gap flows / Q_s |')
    w('|---|---|---:|---:|---|---|---|---|---|')
    for r in F5['python'][v]:
        w('| %s | %g | %d | %d | %s | %s | %.7f | %s | %.5f |' % (r['run'], r['scale'], r['n_tets'], r['n_dofs'],
                                                                e(r['minres_residual'], 1), e(r['Q_in'], 6), r['F'],
                                                                e(r['imbalance'], 1), r['Q_gap_sum_over_Qs']))
    g = G[v + '_python']
    for nm, t in (('F, h = N^(−1/3)', g['F']), ('Q_in, h = N^(−1/3)', g['Q_in']),
                  ('F, h = mesh scale (the October definition)', g['F_by_scale_parameter'])):
        if t.get('p') is None:
            w('- %s: %s' % (nm, ('oscillates across the three meshes within %.1e (relative)' % t['spread_rel']) if not t.get('monotone') else 'no observed order (the change between the two finer meshes is as large as between the two coarser ones, so the meshes are not in the asymptotic range for this quantity)'))
            continue
        w('- %s: r21 %.3f, r32 %.3f, observed order p = %.2f, extrapolated %s, GCI_fine (Fs 1.25) %s, u_num %s '
          '(Fs 3: %s)' % (nm, t['r21'], t['r32'], t['p'], ('%.6f' % t['extrapolated']) if nm.startswith('F')
                          else e(t['extrapolated'], 5), e(t['GCI_fine'], 2), e(t['u_num'], 2), e(t['u_num_Fs3'], 2)))
    w('')
w('## 3. Five-gap slab: the two codes\n')
w('| | V1 | V3 |')
w('|---|---|---|')
cm = F5['compare']
rows = [('F, COMSOL coarse', 'F_comsol', '%.6f'), ('u_num, COMSOL (two-grid)', 'u_num_comsol', '%.2e'),
        ('F, COMSOL extrapolated (p = 2)', 'F_comsol_extrapolated', '%.6f'),
        ('F, Python CFD finest', 'F_python_finest', '%.6f'),
        ('F, Python CFD extrapolated', 'F_python_extrapolated', '%.6f'),
        ('u_num, Python CFD (three-grid, Fs 1.25)', 'u_num_python', '%.2e'),
        ('Python CFD finest − COMSOL coarse', 'dF_python_finest_minus_comsol', '%+.2e'),
        ('Python CFD extrapolated − COMSOL coarse', 'dF_python_ext_minus_comsol', '%+.2e'),
        ('Python CFD extrapolated − COMSOL extrapolated', 'dF_extrapolations', '%+.2e'),
        ('Q_in, Python CFD finest / COMSOL coarse', 'Q_in_ratio_python_finest', '%.5f'),
        ('Q_in extrapolated, COMSOL', 'Q_in_comsol_extrapolated', '%.5e'),
        ('Q_in extrapolated, Python CFD', 'Q_in_python_extrapolated', '%.5e')]
for lab, k, f in rows:
    if all(k in cm.get(v, {}) for v in ('V1', 'V3')):
        w('| %s | %s | %s |' % (lab, *[(f % cm[v][k]) if cm[v][k] is not None else 'no observed order (not in the asymptotic range)'
                                      for v in ('V1', 'V3')]))
for v in ('V1', 'V3'):
    if 'dp_rel_diff' not in cm.get(v, {}):
        continue
    w('\n%s, per gap (1 to 5), Python CFD finest against COMSOL coarse: pressure difference %s; flow through the gap '
      '%s. Fraction of the arriving center flow withdrawn by each gap: COMSOL %s; Python CFD %s.' % (
          v, ', '.join('%+.2f%%' % (100 * x) for x in cm[v]['dp_rel_diff']),
          ', '.join('%+.2f%%' % (100 * x) for x in cm[v]['Q_gap_rel_diff']),
          ', '.join('%.4f' % x for x in cm[v]['f_gap_comsol']), ', '.join('%.4f' % x for x in cm[v]['f_gap_python'])))
    fd = cm[v].get('field_python_finest_vs_comsol_coarse')
    fc = cm[v]['comsol_coarse_vs_extra_coarse_field']
    if fd:
        w('Mid-depth in-plane velocity: Python CFD finest vs COMSOL coarse, relative L2 %.2e, largest difference %.2e '
          'of the peak speed; COMSOL coarse vs extra coarse, %.2e and %.2e.' % (fd['rel_l2'], fd['max_abs_over_max_speed'],
                                                                                 fc['rel_l2'], fc['max_abs_over_max_speed']))
w('\nPressure-difference half-lives (gaps per halving, fitted on all five probes and on the first four), and the step '
  'ratios:\n')
w('| | all five | first four | step ratios |')
w('|---|---|---|---|')
for k, h in F5['half_lives'].items():
    w('| %s | %.4f | %.4f | %s |' % (k, h['all5'], h['first4'], ', '.join('%.3f' % x for x in h['step_ratios'])))
w('\nValidation comparison with Dinh et al. (V&V 20: E = S − D, u_val = √(u_num² + u_input² + u_D²)):\n')
w('| | E | u_D | u_num | u_val | E/u_D | E/u_val | u_val over u_D | u_D/u_num |')
w('|---|---|---|---|---|---|---|---|---|')
for v in ('V1', 'V3'):
    x = cm.get(v, {}).get('validation_comsol')
    if x:
        w('| %s | %+.5f | %.3f | %.2e | %.5f | %+.3f | %+.3f | +%.2f%% | %.1f |' % (v, x['E'], x['u_D'], x['u_num'],
                                                                              x['u_val'], x['E_over_uD'],
                                                                              x['E_over_uval'], x['uval_excess_pct'],
                                                                              x['uD_over_unum']))
w('\n## 4. Single gap\n')
w('COMSOL (one mesh per run), skim width at x = 75 µm by the same routine as Python CFD:\n')
w('| Case | f_q = Q_s/Q_in | native grid | campaign resampling | exact duct law | native / law |')
w('|---|---|---|---|---|---|')
for k, r in SG['comsol'].items():
    if isinstance(r, dict):
        w('| %s | %s | %.5f | %.5f | %.5f | %.5f |' % (k, e(r['f_q'], 6), r['native'], r['resampled'], r['duct_law'],
                                                   r['native_over_law']))
w('\nThe developed inlet changes Run B\'s skim width, relative to the duct law at each fraction, by %+.3f%% (native '
  'grid) and %+.3f%% (resampled) in COMSOL; in Python CFD by %s.\n' % (
      100 * SG['comsol']['inlet_effect_B_native'], 100 * SG['comsol']['inlet_effect_B_resampled'],
      ', '.join('%+.3f%% (scale %s)' % (100 * v, s) for s, v in SG['inlet_effect_B_python'].items()) or '—'))
w('Python CFD, each run against COMSOL on the same points:\n')
w('| Run | Inlet | Scale | Tets | residual | skim (µm) | COMSOL | ratio | ratio, resampled | / law | upstream field, rel. L2 | trace (µm) | trace, COMSOL field |')
w('|---|---|---|---:|---|---|---|---|---|---|---|---|---|')
for k, r in sorted(SG['runs'].items(), key=lambda t: (t[0].split('_s')[0], -t[1]['scale'])):
    s = r['skim']; m = r['middepth']
    tc = m['trace_comsol'].get('delta_at_x_report')
    w('| %s | %s | %g | %d | %s | %.5f | %.5f | %.5f | %.5f | %.5f | %s | %.4f | %s |' % (
        k, r['inlet'], r['scale'], r['n_tets'], e(r['residual'], 1), s['python']['native'], s['comsol']['native'],
        s['python_over_comsol_native'], s['python_over_comsol_resampled'], s['python']['native_over_law'],
        e(s['upstream_field']['rel_l2'], 1), m['trace_python']['delta_at_x_report'],
        '%.4f' % tc if tc is not None else 'not resolved on the 0.1 µm export grid'))
if SG.get('grid_python'):
    w('\nThree-mesh estimates of Python CFD (h = N^(−1/3)):\n')
    for fam, g in SG['grid_python'].items():
        for nm in ('delta', 'trace'):
            t = g[nm]
            if t.get('p') is None:
                w('- %s, %s: %s' % (fam, nm, ('oscillates across the three meshes within %.1e (relative), so no extrapolation' % t['spread_rel']) if not t.get('monotone') else 'no observed order (not in the asymptotic range)'))
            else:
                w('- %s, %s: observed order %.2f, extrapolated %.5f, GCI_fine (Fs 1.25) %s' % (
                    fam, nm, t['p'], t['extrapolated'], e(t['GCI_fine'], 2)))
open(os.path.join(root, 'cfd', 'results', 'COMPARISON.md'), 'w', encoding='utf-8').write('\n'.join(L) + '\n')
print('written', os.path.join(root, 'cfd', 'results', 'COMPARISON.md'))
